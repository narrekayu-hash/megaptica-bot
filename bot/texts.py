async def t(chat_id: int, key: str, **values) -> str:
    """Текст для чата: свой из панели или стандартный, с подставленными значениями."""
    custom = (await settings.get(chat_id))["texts"].get(key) if chat_id else None
    raw = custom or TEXTS[key].default
    for name, value in values.items():
        raw = raw.replace("{" + name + "}", str(value))
    return raw


def sample(key: str, raw: str) -> str:
    """Текст с примерами вместо подстановок — для предпросмотра в панели."""
    for name, (_, example) in TEXTS[key].vars.items():
        raw = raw.replace("{" + name + "}", example)
    return raw
